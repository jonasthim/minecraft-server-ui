package mapdata

import (
	"bytes"
	"compress/gzip"
	"compress/zlib"
	"context"
	"encoding/binary"
	"fmt"
	"github.com/pierrec/lz4/v4"
	"io"
	"math/bits"
)

type contextReader struct {
	ctx context.Context
	r   io.Reader
}

func (r contextReader) Read(p []byte) (int, error) {
	if e := r.ctx.Err(); e != nil {
		return 0, e
	}
	if len(p) > 32768 {
		p = p[:32768]
	}
	return r.r.Read(p)
}
func (r contextReader) ReadByte() (byte, error) {
	if e := r.ctx.Err(); e != nil {
		return 0, e
	}
	if br, ok := r.r.(io.ByteReader); ok {
		return br.ReadByte()
	}
	var b [1]byte
	_, e := io.ReadFull(r.r, b[:])
	return b[0], e
}

func decompress(ctx context.Context, codec byte, b []byte) ([]byte, error) {
	if e := ctx.Err(); e != nil {
		return nil, e
	}
	if codec == 4 {
		return javaLZ4(ctx, b)
	}
	var r io.ReadCloser
	var e error
	input := bytes.NewReader(b)
	src := contextReader{ctx, input}
	switch codec {
	case 1:
		r, e = gzip.NewReader(src)
	case 2:
		r, e = zlib.NewReader(src)
	case 3:
		r = io.NopCloser(src)
	default:
		return nil, errUnsupported
	}
	if e != nil {
		return nil, fmt.Errorf("compression header: %w", errCorrupt)
	}
	defer r.Close()
	out, e := io.ReadAll(io.LimitReader(contextReader{ctx, r}, maxDecoded+1))
	if e != nil {
		if ctx.Err() != nil {
			return nil, ctx.Err()
		}
		return nil, fmt.Errorf("decompression: %w", errCorrupt)
	}
	if input.Len() != 0 {
		return nil, errCorrupt
	}
	if len(out) > maxDecoded {
		return nil, errCorrupt
	}
	return out, nil
}

// Java LZ4Block framing is distinct from the LZ4 standard frame format. Only
// framing is implemented here; the reviewed library decompresses bounded blocks.
func javaLZ4(ctx context.Context, b []byte) ([]byte, error) {
	out := make([]byte, 0, min(len(b)*2, maxDecoded))
	for {
		if e := ctx.Err(); e != nil {
			return nil, e
		}
		if len(b) < 21 || string(b[:8]) != "LZ4Block" {
			return nil, errCorrupt
		}
		method := b[8] & 0xf0
		limit := 1 << ((b[8] & 15) + 10)
		clen := int64(binary.LittleEndian.Uint32(b[9:]))
		olen := int64(binary.LittleEndian.Uint32(b[13:]))
		check := binary.LittleEndian.Uint32(b[17:])
		b = b[21:]
		if method != 0x10 && method != 0x20 || olen > int64(limit) || olen > int64(maxDecoded-len(out)) || clen > int64(len(b)) || clen > maxDecoded || method == 0x10 && clen != olen {
			return nil, errCorrupt
		}
		if olen == 0 || clen == 0 {
			if olen != 0 || clen != 0 || check != 0 || len(b) != 0 {
				return nil, errCorrupt
			}
			return out, nil
		}
		block := make([]byte, int(olen))
		if method == 0x10 {
			copy(block, b[:int(clen)])
		} else {
			n, e := lz4.UncompressBlock(b[:int(clen)], block)
			if e != nil || n != len(block) {
				return nil, errCorrupt
			}
		}
		// Java StreamingXXHash32.asChecksum exposes only its lower28bits.
		if xxh32(block, 0x9747b28c)&0x0fffffff != check {
			return nil, errCorrupt
		}
		out = append(out, block...)
		b = b[int(clen):]
	}
}

// Original one-shot implementation of the public XXH32 algorithm specification.
// Oracle vectors are generated by the primary C libxxhash, never by this code.
func xxh32(b []byte, seed uint32) uint32 {
	const p1 uint32 = 2654435761
	const p2 uint32 = 2246822519
	const p3 uint32 = 3266489917
	const p4 uint32 = 668265263
	const p5 uint32 = 374761393
	n := len(b)
	var h uint32
	if n >= 16 {
		v := [4]uint32{seed + p1 + p2, seed + p2, seed, seed - p1}
		for len(b) >= 16 {
			for i := 0; i < 4; i++ {
				v[i] = bits.RotateLeft32(v[i]+binary.LittleEndian.Uint32(b[i*4:])*p2, 13) * p1
			}
			b = b[16:]
		}
		h = bits.RotateLeft32(v[0], 1) + bits.RotateLeft32(v[1], 7) + bits.RotateLeft32(v[2], 12) + bits.RotateLeft32(v[3], 18)
	} else {
		h = seed + p5
	}
	h += uint32(n)
	for len(b) >= 4 {
		h = bits.RotateLeft32(h+binary.LittleEndian.Uint32(b)*p3, 17) * p4
		b = b[4:]
	}
	for _, v := range b {
		h = bits.RotateLeft32(h+uint32(v)*p5, 11) * p1
	}
	h ^= h >> 15
	h *= p2
	h ^= h >> 13
	h *= p3
	h ^= h >> 16
	return h
}
