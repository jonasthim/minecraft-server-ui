// Package candidate produces bounded, deterministic release candidates. It uses
// only the Go standard library; shipping selfupdate compatibility is tested
// against the application's real verifier and stager.
package candidate

import (
	"bytes"
	"crypto/ed25519"
	"crypto/sha256"
	"encoding/base64"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"regexp"
	"strconv"
	"strings"
	"time"
)

const MaxBinaryBytes int64 = 256 << 20
const MaxAssetBytes int64 = 1 << 20
const MaxBootstrapBytes = 32 << 10
const MaxBundleBytes int64 = 2*MaxBinaryBytes + 16*MaxAssetBytes
const validity = 30 * 24 * time.Hour

var versionRE = regexp.MustCompile(`^v(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)$`)
var repositoryRE = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9-]{0,38}/[A-Za-z0-9][A-Za-z0-9_.-]{0,99}$`)
var keyRE = regexp.MustCompile(`^[A-Za-z0-9_-]{1,64}$`)

type asset struct {
	name string
	mode uint32
}

var linuxAssets = []asset{{"install.sh", 0755}, {"unitctl", 0755}, {"minecraft@.service", 0644}, {"minecraft-ui.service", 0644}, {"sudoers", 0440}, {"minecraft-ui-update@.service", 0644}, {"minecraft-ui-update-recovery.service", 0644}, {"minecraft-ui-update.conf", 0644}, {"update-trust.example.json", 0644}, {"NOTICE", 0644}}
var windowsAssets = []asset{{"install.ps1", 0644}}

func members(platform string) []asset {
	binary, updater := "minecraft-ui", "selfupdate"
	assets := linuxAssets
	if platform == "windows" {
		binary += ".exe"
		updater += ".exe"
		assets = windowsAssets
	}
	out := []asset{{binary, 0755}, {updater, 0755}, {"LICENSE", 0644}, {"THIRD_PARTY_NOTICES.txt", 0644}}
	return append(out, assets...)
}
func archiveName(platform string, bootstrap bool) string {
	prefix := "minecraft-ui-"
	if bootstrap {
		prefix += "bootstrap-"
	}
	extension := ".tar.gz"
	if platform == "windows" {
		extension = ".zip"
	}
	return prefix + platform + "-amd64" + extension
}

type Trust struct {
	Repository string
	PublicKeys map[string]ed25519.PublicKey
}
type Signature struct {
	KeyID     string `json:"key_id"`
	Signature string `json:"signature"`
}
type Member struct {
	Name   string `json:"name"`
	Size   int64  `json:"size"`
	SHA256 string `json:"sha256"`
	Mode   uint32 `json:"mode"`
}
type Bundle struct {
	OS      string   `json:"os"`
	Arch    string   `json:"arch"`
	Name    string   `json:"name"`
	Size    int64    `json:"size"`
	SHA256  string   `json:"sha256"`
	Members []Member `json:"members"`
}
type Bootstrap struct {
	Format      int       `json:"format"`
	Purpose     string    `json:"purpose"`
	Repository  string    `json:"repository"`
	Version     string    `json:"version"`
	PublishedAt time.Time `json:"published_at"`
	ExpiresAt   time.Time `json:"expires_at"`
	Schema      int64     `json:"schema"`
	Trust       string    `json:"trust"`
	Artifacts   []Bundle  `json:"artifacts"`
}

// Update mirrors the shipping selfupdate.Manifest contract. The producer never
// extends it with bootstrap fields or changes the unchanged-schema rule.
type Update struct {
	Format       int              `json:"format"`
	Repository   string           `json:"repository"`
	Version      string           `json:"version"`
	PublishedAt  time.Time        `json:"published_at"`
	ExpiresAt    time.Time        `json:"expires_at"`
	SchemaBefore int64            `json:"schema_before"`
	SchemaAfter  int64            `json:"schema_after"`
	Artifacts    []UpdateArtifact `json:"artifacts"`
}
type UpdateArtifact struct {
	OS           string `json:"os"`
	Arch         string `json:"arch"`
	Name         string `json:"name"`
	Size         int64  `json:"size"`
	SHA256       string `json:"sha256"`
	BinarySize   int64  `json:"binary_size"`
	BinarySHA256 string `json:"binary_sha256"`
}

func validVersion(s string) bool {
	if !versionRE.MatchString(s) {
		return false
	}
	for _, p := range strings.Split(s[1:], ".") {
		if _, e := strconv.ParseUint(p, 10, 64); e != nil {
			return false
		}
	}
	return true
}
func digest(b []byte) string { h := sha256.Sum256(b); return hex.EncodeToString(h[:]) }
func validHash(s string) bool {
	b, e := hex.DecodeString(s)
	return e == nil && len(b) == 32 && hex.EncodeToString(b) == s
}
func canonical(v any) ([]byte, error) { b, e := json.Marshal(v); return append(b, '\n'), e }

// The v1 bootstrap wire format requires canonical JSON generated by this
// package. Exact re-encoding also rejects duplicates, unknown fields and tails.
func decode(body []byte, v any) error {
	d := json.NewDecoder(bytes.NewReader(body))
	d.DisallowUnknownFields()
	if e := d.Decode(v); e != nil {
		return e
	}
	if _, e := d.Token(); !errors.Is(e, io.EOF) {
		return errors.New("trailing JSON")
	}
	encoded, e := canonical(v)
	if e != nil || !bytes.Equal(encoded, body) {
		return errors.New("noncanonical bootstrap JSON")
	}
	return nil
}
func sign(body []byte, id string, key ed25519.PrivateKey) ([]byte, error) {
	return canonical(Signature{KeyID: id, Signature: base64.StdEncoding.EncodeToString(ed25519.Sign(key, body))})
}
func validateBundle(a Bundle) error {
	if (a.OS != "linux" && a.OS != "windows") || a.Arch != "amd64" || a.Name != archiveName(a.OS, true) || a.Size < 1 || a.Size > MaxBundleBytes || !validHash(a.SHA256) {
		return errors.New("invalid bootstrap bundle identity or bounds")
	}
	expected := members(a.OS)
	if len(a.Members) != len(expected) {
		return errors.New("bootstrap must contain exact platform member allowlist")
	}
	for i, m := range a.Members {
		limit := MaxAssetBytes
		if i < 2 {
			limit = MaxBinaryBytes
		}
		if m.Name != expected[i].name || m.Mode != expected[i].mode || m.Size < 1 || m.Size > limit || !validHash(m.SHA256) {
			return fmt.Errorf("invalid bootstrap member at index %d", i)
		}
	}
	return nil
}

// VerifyBootstrap authenticates exact metadata bytes against independently
// configured trust. The caller must pin requested version and compare Schema to
// its migration policy; the bootstrap format does not authorize activation.
func VerifyBootstrap(trust Trust, body, envelope []byte, version string, now time.Time) (Bootstrap, error) {
	var m Bootstrap
	if !repositoryRE.MatchString(trust.Repository) || bytes.Contains([]byte(trust.Repository), []byte("..")) || len(trust.PublicKeys) < 1 || len(trust.PublicKeys) > 16 {
		return m, errors.New("bootstrap trust is not configured")
	}
	for id, key := range trust.PublicKeys {
		if !keyRE.MatchString(id) || len(key) != ed25519.PublicKeySize {
			return m, errors.New("invalid bootstrap trust")
		}
	}
	if len(body) < 1 || len(body) > MaxBootstrapBytes || len(envelope) > 1024 {
		return m, errors.New("bootstrap metadata exceeds bounds")
	}
	var s Signature
	if e := decode(envelope, &s); e != nil {
		return m, errors.New("invalid bootstrap signature envelope")
	}
	key, ok := trust.PublicKeys[s.KeyID]
	sig, e := base64.StdEncoding.Strict().DecodeString(s.Signature)
	if !ok || e != nil || !ed25519.Verify(key, body, sig) {
		return m, errors.New("bootstrap signature verification failed")
	}
	if e := decode(body, &m); e != nil {
		return m, fmt.Errorf("invalid bootstrap metadata: %w", e)
	}
	if m.Format != 1 || m.Purpose != "minecraft-ui-bootstrap" || m.Repository != trust.Repository || m.Version != version || !validVersion(m.Version) || m.Schema < 1 || (m.Trust != "DEVELOPMENT ONLY" && m.Trust != "OWNER SIGNED") {
		return m, errors.New("bootstrap identity does not match requested source or version")
	}
	if m.PublishedAt.IsZero() || m.PublishedAt.After(now) || !m.ExpiresAt.After(now) || !m.ExpiresAt.After(m.PublishedAt) || m.ExpiresAt.Sub(m.PublishedAt) > validity {
		return m, errors.New("bootstrap validity window is not current")
	}
	if len(m.Artifacts) != 2 || m.Artifacts[0].OS != "linux" || m.Artifacts[1].OS != "windows" {
		return m, errors.New("bootstrap requires both ordered target platforms")
	}
	for _, a := range m.Artifacts {
		if e := validateBundle(a); e != nil {
			return m, e
		}
	}
	return m, nil
}
